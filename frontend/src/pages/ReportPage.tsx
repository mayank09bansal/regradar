import { api } from "../api";
import Markdown from "../components/Markdown";
import RunScope from "../components/RunScope";
import { Card, EmptyState } from "../components/ui";

/** The Output Agent's report, with download and print options. */
export default function ReportPage() {
  return (
    <RunScope title="Final Report" subtitle="Generated by the Output Agent at the end of the run.">
      {(run) =>
        run.report ? (
          <Card
            actions={
              <div className="row gap-s">
                <a className="btn btn-secondary" href={api.reportMarkdownUrl(run.id)}>Download Markdown</a>
                <button className="btn btn-secondary" onClick={() => window.print()}>Print / Save as PDF</button>
              </div>
            }
          >
            <Markdown source={run.report.markdown} />
          </Card>
        ) : <EmptyState title="This run has no report">{run.error && <p>{run.error}</p>}</EmptyState>
      }
    </RunScope>
  );
}
